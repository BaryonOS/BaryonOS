set -eu
out=/tmp/nieuw-os-storage-zfs-20261102
win=/mnt/c/Users/simon/Documents/Codex/2026-11-02/native-storage-gate/openzfs
mkdir -p "$win/images" "$win/logs"
sha256sum "$out/images/mirror/nieuwos_n3.0a" "$out/images/mirror/nieuwos_n3.1a" > "$out/logs/baseline-sha256.txt"
rm -f "$out/logs/windows-copy-sha256.txt" "$out/logs/windows-copy-sha256.pending"
cp --sparse=always "$out/images/mirror/nieuwos_n3.0a" "$win/images/nieuwos_n3.0a"
cp --sparse=always "$out/images/mirror/nieuwos_n3.1a" "$win/images/nieuwos_n3.1a"
sha256sum "$win/images/nieuwos_n3.0a" "$win/images/nieuwos_n3.1a" > "$out/logs/windows-copy-sha256.pending"
if ! cmp -s <(cut -d ' ' -f 1 "$out/logs/baseline-sha256.txt") <(cut -d ' ' -f 1 "$out/logs/windows-copy-sha256.pending"); then
  rm -f "$out/logs/windows-copy-sha256.pending"
  printf 'Baseline and copied image hashes differ\n' >&2
  exit 1
fi
mv "$out/logs/windows-copy-sha256.pending" "$out/logs/windows-copy-sha256.txt"
cp "$out/logs/create-bounded"* "$out/logs/baseline-sha256.txt" "$out/logs/windows-copy-sha256.txt" "$win/logs/"
cat "$out/logs/windows-copy-sha256.txt"
export LD_LIBRARY_PATH="$out/root/usr/lib/x86_64-linux-gnu"
export PATH="$out/root/usr/sbin:$PATH"
export MALLOC_ARENA_MAX=2
export ZFS_STACK_SIZE=131072
ulimit -c 0
ulimit -v 8388608
if [ ! -f "$out/logs/baseline-pool-guid.txt" ]; then
  printf 'Missing baseline pool GUID; run a successful create first\n' >&2
  exit 1
fi
pool_guid=$(cat "$out/logs/baseline-pool-guid.txt")
case "$pool_guid" in
  ''|*[!0-9]*|0) printf 'Invalid or missing baseline pool GUID\n' >&2; exit 1 ;;
esac
# Recheck both source labels against the GUID generated by create.
for member in 0 1; do
  timeout --kill-after=5s 60s "$out/root/usr/sbin/zdb" -l "$out/images/mirror/nieuwos_n3.${member}a" > "$out/logs/fresh-label-${member}.txt"
  python3 - "$out/logs/fresh-label-${member}.txt" "$pool_guid" <<'PYGUID'
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text()
names = set(re.findall(r"^\s*name: '([^']+)'\s*$", text, re.M))
guids = set(re.findall(r'^\s*pool_guid: ([0-9]+)\s*$', text, re.M))
if names != {'nieuwos_n3'} or guids != {sys.argv[2]}:
    raise SystemExit('Baseline pool GUID or name does not match member label')
PYGUID
done
set +e
/usr/bin/time -v -o "$out/logs/fresh-zdb-time.txt" timeout --kill-after=5s 60s "$out/root/usr/sbin/zdb" -bcc -G -d -Y -e -y -p "$out/images/mirror" "$pool_guid" > "$out/logs/fresh-zdb.txt" 2>&1
rc=$?
printf '%s\n' "$rc" > "$out/logs/fresh-zdb-exit.txt"
tail -30 "$out/logs/fresh-zdb.txt"
exit "$rc"