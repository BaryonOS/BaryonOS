//! Original geometric icons on a 24-unit grid. No font symbols or bitmap placeholders.
use crate::{Canvas, Rect};
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Icon {
    Material,
    Folder,
    Search,
    Apps,
    Close,
    Minimize,
    Maximize,
    Lock,
    User,
    Key,
    Fingerprint,
    ChevronLeft,
    ChevronRight,
    Check,
    Settings,
    Power,
    Add,
    Refresh,
    Network,
    Shield,
}
pub(crate) fn draw(c: &mut Canvas<'_>, r: Rect, icon: Icon, color: u32, stroke: u32) {
    if r.width == 0 || r.height == 0 || r.width > 256 || r.height > 256 || !r.intersects(c.bounds())
    {
        return;
    }
    let p = |x: i32, y: i32| {
        (
            r.x.saturating_add((i64::from(x) * i64::from(r.width) / 24) as i32),
            r.y.saturating_add((i64::from(y) * i64::from(r.height) / 24) as i32),
        )
    };
    let mut line = |a: (i32, i32), b: (i32, i32)| {
        let (a, b) = (p(a.0, a.1), p(b.0, b.1));
        c.line(a.0, a.1, b.0, b.1, stroke.max(1), color);
    };
    let paths: &[&[(i32, i32)]] = match icon {
        Icon::Material => &[
            &[(6, 3), (14, 3), (19, 8), (19, 21), (6, 21), (6, 3)],
            &[(14, 3), (14, 8), (19, 8)],
            &[(9, 12), (16, 12)],
            &[(9, 16), (15, 16)],
        ],
        Icon::Folder => &[
            &[(3, 6), (10, 6), (12, 9), (21, 9), (20, 20), (4, 20), (3, 6)],
            &[(3, 10), (20, 10)],
        ],
        Icon::Search => &[
            &[
                (10, 3),
                (14, 4),
                (17, 7),
                (17, 12),
                (14, 16),
                (9, 17),
                (5, 15),
                (3, 11),
                (4, 7),
                (7, 4),
                (10, 3),
            ],
            &[(16, 16), (21, 21)],
        ],
        Icon::Apps => &[
            &[(4, 4), (9, 4), (9, 9), (4, 9), (4, 4)],
            &[(15, 4), (20, 4), (20, 9), (15, 9), (15, 4)],
            &[(4, 15), (9, 15), (9, 20), (4, 20), (4, 15)],
            &[(15, 15), (20, 15), (20, 20), (15, 20), (15, 15)],
        ],
        Icon::Close => &[&[(6, 6), (18, 18)], &[(18, 6), (6, 18)]],
        Icon::Minimize => &[&[(5, 17), (19, 17)]],
        Icon::Maximize => &[&[(5, 5), (19, 5), (19, 19), (5, 19), (5, 5)]],
        Icon::Lock => &[
            &[(6, 10), (18, 10), (18, 21), (6, 21), (6, 10)],
            &[(8, 10), (8, 6), (10, 3), (14, 3), (16, 6), (16, 10)],
            &[(12, 14), (12, 17)],
        ],
        Icon::User => &[
            &[
                (12, 3),
                (15, 4),
                (17, 7),
                (16, 10),
                (12, 12),
                (8, 10),
                (7, 7),
                (9, 4),
                (12, 3),
            ],
            &[(3, 21), (4, 17), (8, 15), (16, 15), (20, 17), (21, 21)],
        ],
        Icon::Key => &[
            &[
                (8, 4),
                (12, 5),
                (14, 8),
                (13, 12),
                (9, 14),
                (5, 12),
                (3, 8),
                (5, 5),
                (8, 4),
            ],
            &[(13, 13), (21, 21)],
            &[(17, 17), (20, 14)],
            &[(20, 20), (22, 18)],
        ],
        Icon::Fingerprint => &[
            &[(4, 10), (5, 6), (9, 3), (14, 3), (18, 5), (20, 9)],
            &[(4, 15), (6, 18)],
            &[(7, 11), (8, 7), (12, 6), (16, 8), (17, 12), (17, 18)],
            &[(10, 19), (10, 12), (12, 10), (14, 12), (14, 21)],
            &[(20, 13), (20, 17), (18, 21)],
        ],
        Icon::ChevronLeft => &[&[(15, 5), (8, 12), (15, 19)]],
        Icon::ChevronRight => &[&[(9, 5), (16, 12), (9, 19)]],
        Icon::Check => &[&[(4, 12), (9, 17), (20, 6)]],
        Icon::Settings => &[
            &[
                (8, 3),
                (16, 3),
                (17, 7),
                (21, 9),
                (21, 15),
                (17, 17),
                (16, 21),
                (8, 21),
                (7, 17),
                (3, 15),
                (3, 9),
                (7, 7),
                (8, 3),
            ],
            &[(12, 8), (16, 12), (12, 16), (8, 12), (12, 8)],
        ],
        Icon::Power => &[
            &[(12, 2), (12, 12)],
            &[
                (7, 5),
                (3, 9),
                (3, 15),
                (7, 20),
                (13, 22),
                (19, 19),
                (21, 14),
                (20, 9),
                (17, 5),
            ],
        ],
        Icon::Add => &[&[(5, 12), (19, 12)], &[(12, 5), (12, 19)]],
        Icon::Refresh => &[
            &[
                (20, 8),
                (17, 4),
                (12, 3),
                (7, 5),
                (4, 9),
                (4, 15),
                (8, 19),
                (14, 21),
                (19, 18),
            ],
            &[(20, 3), (20, 8), (15, 8)],
        ],
        Icon::Network => &[
            &[(3, 8), (7, 5), (12, 4), (17, 5), (21, 8)],
            &[(6, 12), (9, 10), (15, 10), (18, 12)],
            &[(9, 16), (12, 14), (15, 16)],
            &[(12, 20), (12, 20)],
        ],
        Icon::Shield => &[
            &[
                (12, 2),
                (21, 6),
                (20, 14),
                (16, 19),
                (12, 22),
                (8, 19),
                (4, 14),
                (3, 6),
                (12, 2),
            ],
            &[(7, 11), (11, 15), (17, 8)],
        ],
    };
    for path in paths {
        for pair in path.windows(2) {
            line(pair[0], pair[1]);
        }
    }
}
