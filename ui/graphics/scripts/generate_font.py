#!/usr/bin/env python3
"""Offline fixed Open Sans 1.10 atlas. Native code never parses a font file."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'regular': ('OpenSans-Regular.ttf', 'e64e508b2aa2880f907e470c4550980ec4c0694d103a43f36150ac3f93189bee'),
    'semibold': ('OpenSans-Semibold.ttf', 'aa3b0ef53db12e3d45094030cac0e69d384e44cc5978643dd4390041cad546e2'),
}
CHARS = [chr(n) for n in range(32, 127)] + [chr(n) for n in range(160, 256)] + ['\u2026', '\u20ac', '\ufffd']
SPECS = [('regular',12),('regular',16),('regular',24),('regular',32),('semibold',16),('semibold',32),('semibold',64)]

def main():
    data=bytearray(); rows=[]; glyphs=[]; fonts=[]; source_meta={}
    for weight,(name,digest) in SOURCES.items():
        path=Path('/usr/share/fonts/truetype/open-sans')/name
        assert hashlib.sha256(path.read_bytes()).hexdigest()==digest
        source_meta[weight]={'source':str(path),'sha256':digest,'version':'1.10','copyright':'Digitized data copyright (c) 2010-2011 Google Corporation','license':'Apache-2.0'}
    for weight,size in SPECS:
        f=ImageFont.truetype('/usr/share/fonts/truetype/open-sans/'+SOURCES[weight][0],size)
        ascent,descent=f.getmetrics();first=len(glyphs)
        for ch in CHARS:
            box=f.getbbox(ch,anchor='ls');left,top,right,bottom=box;w=right-left;h=bottom-top
            assert 0<=w<=96 and 0<=h<=96 and -128<=left<128 and -128<=ascent+top<128
            mask=Image.new('L',(max(1,w),max(1,h)),0)
            if w and h:ImageDraw.Draw(mask).text((-left,-top),ch,font=f,fill=255,anchor='ls',stroke_width=0)
            begin=len(data);row=len(rows)
            for y in range(h):
                rows.append(len(data)-begin)
                x=0
                while x<w:
                    alpha=(mask.getpixel((x,y))+8)//17;alpha=min(15,alpha);run=1
                    while x+run<w and run<16 and min(15,(mask.getpixel((x+run,y))+8)//17)==alpha:run+=1
                    data.append(((run-1)<<4)|alpha);x+=run
            rows.append(len(data)-begin)
            assert len(data)-begin<65536
            glyphs.append((begin,row,left,ascent+top,w,h,round(f.getlength(ch)*64)))
        fonts.append((first,size,ascent+descent))
    (ROOT/'assets/open-sans-atlas.rle').write_bytes(data)
    rs=['// Generated by scripts/generate_font.py from the fixed licensed sources.','use super::{FontRecord, Glyph};',f'pub const GLYPH_COUNT: usize = {len(CHARS)};', 'pub static CHARS: [u32; GLYPH_COUNT] = ['+','.join(str(ord(c)) for c in CHARS)+'];',f'pub static FONTS: [FontRecord; {len(fonts)}] = [']
    rs += [f'FontRecord{{first:{a},size:{b},height:{c}}},' for a,b,c in fonts];rs+= ['];',f'pub static GLYPHS: [Glyph; {len(glyphs)}] = [']
    rs += ['Glyph{offset:%s,rows:%s,left:%s,top:%s,width:%s,height:%s,advance:%s},'%g for g in glyphs];rs += ['];',f'pub static ROWS: [u16; {len(rows)}] = [']
    for i in range(0,len(rows),24):rs.append(','.join(str(v) for v in rows[i:i+24])+',')
    rs+= ['];','pub static DATA: &[u8] = include_bytes!("../assets/open-sans-atlas.rle");']
    (ROOT/'src/atlas.rs').write_text('\n'.join(rs)+'\n')
    meta={'font':'Open Sans','sources':source_meta,'specs':SPECS,'characters':len(CHARS),'glyphs':len(glyphs),'row_offsets':len(rows),'data_bytes':len(data),'data_sha256':hashlib.sha256(data).hexdigest(),'encoding':'Rows of (run length minus1) in high nibble and 4bit coverage in low nibble; 16 levels','native_parser':'None; fixed checked metadata and bounded row decoder','build_time_only':'Pillow/FreeType; not native dependencies'}
    (ROOT/'assets/font-provenance.json').write_text(json.dumps(meta,indent=2)+'\n')
    print(json.dumps({k:meta[k] for k in ['characters','glyphs','row_offsets','data_bytes','data_sha256']}))
if __name__=='__main__':main()
