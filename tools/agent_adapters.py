#!/usr/bin/env python3
"""Generate the Claude, Codex and Copilot adapters of the specialist role contracts.

The canonical contract is `.agents/roles/specialist_<x>.md` in the format agreed
for CI-C1: first line `# specialist_<x>`, the first sentence of the first
paragraph is the description, and exactly one ``Tool class: `<class>` `` line.
The hand-written `os_*` adapters are out of scope until they carry a class.

`--check` (the default) lists stale and orphaned adapters and exits 1 on drift;
`--write` regenerates them. An unknown or missing class is an error, never a
default: this generator only maps classes whose tool limits have been designed.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = ".agents/roles"
# Copilot surface tools per class. `coordinator` gets no Copilot profile: the
# coordinator contracts state the Copilot cloud agent is unsuitable for them.
# `read-only` has no mapping until a role needs one, so it is rejected.
COPILOT_TOOLS = {"builder": ["read", "search", "edit", "execute"], "coordinator": None}
# Read-only hosted Graphify tools; `remember` is deliberately absent. The server
# name `graphify` is a repository MCP setting (owner); Copilot ignores unknown names.
GRAPHIFY_READ_ONLY = (
    "recall", "graphify_rank_files", "graphify_find", "graphify_callers",
    "graphify_impact", "graphify_tests_for", "graphify_file_neighbors", "query_graph",
)
PATTERNS = (".claude/agents/specialist-*.md", ".codex/agents/specialist_*.toml",
            ".github/agents/specialist-*.agent.md")


def parse(path: Path) -> tuple[str, str, str]:
    """Return (role, description, tool class) of one contract, or raise ValueError."""
    role = path.stem
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != f"# {role}":
        raise ValueError(f"{path.name}: first line must be '# {role}'")
    paragraph: list[str] = []
    for line in lines[1:]:
        if line.strip():
            paragraph.append(line.strip())
        elif paragraph:
            break
    sentence = re.match(r"(.+?\.)(?:\s|$)", " ".join(paragraph))
    if not sentence:
        raise ValueError(f"{path.name}: no first intro sentence")
    classes = re.findall(r"^Tool class: `([^`]*)`\s*$", "\n".join(lines), re.M)
    if len(classes) != 1:
        raise ValueError(f"{path.name}: needs exactly one 'Tool class:' line, found {len(classes)}")
    if classes[0] not in COPILOT_TOOLS:
        raise ValueError(f"{path.name}: tool class {classes[0]!r} has no adapter mapping")
    return role, sentence[1], classes[0]


def render(role: str, description: str, tool_class: str) -> dict[str, str]:
    """Return {repository path: content} for one contract."""
    slug = role.replace("_", "-")
    contract = f"{ROLES}/{role}.md"
    desc = json.dumps(description, ensure_ascii=False)  # a valid YAML and TOML string
    note = f"Generated by `tools/agent_adapters.py` from `{contract}`; edit the contract, then run `python3 -B tools/agent_adapters.py --write`."
    out = {
        f".claude/agents/{slug}.md": (
            f"---\nname: {slug}\ndescription: {desc}\n---\n\n<!-- {note} -->\n\n"
            f"Read `AGENTS.md` and `{contract}`. Follow the canonical role\n"
            "contract within the assigned scope and existing tool permissions. Use\n"
            "`.agents/skills/development-loop/SKILL.md`. Do not expand permissions.\n"),
        f".codex/agents/{role}.toml": (
            f"# {note.replace('`', '')}\n"
            f'name = "{role}"\ndescription = {desc}\ndeveloper_instructions = """\n'
            f"Read AGENTS.md and {contract}. Follow that canonical role contract within the "
            "assigned write set and available tools. Use .agents/skills/development-loop/SKILL.md. "
            'Report unavailable checks as NOT RUN; do not expand permissions.\n"""\n'),
    }
    tools = COPILOT_TOOLS[tool_class]
    if tools is not None:
        allow = json.dumps(tools + [f"graphify/{t}" for t in GRAPHIFY_READ_ONLY])
        name = f"Specialist {role.removeprefix('specialist_').upper()}"
        out[f".github/agents/{slug}.agent.md"] = (
            f"---\nname: {name}\ndescription: {desc}\ntarget: github-copilot\n"
            f"user-invocable: true\ndisable-model-invocation: true\ntools: {allow}\n---\n\n"
            f"<!-- {note} -->\n\n"
            f"Read `AGENTS.md` and the canonical role contract\n`{contract}`.\n\n"
            "The tool allowlist above is surface-specific. Follow the shared contract within\n"
            "those tools; report unavailable execution as NOT RUN without expanding access.\n"
            "Graphify is read-only on this surface: `remember` is not available.\n")
    return out


def expected(root: Path = ROOT) -> dict[str, str]:
    out: dict[str, str] = {}
    for path in sorted((root / ROLES).glob("specialist_*.md")):
        out.update(render(*parse(path)))
    return out


def drift(root: Path = ROOT) -> list[str]:
    """Stale, missing and orphaned adapters; empty when everything is generated."""
    want = expected(root)
    have = {p.relative_to(root).as_posix() for pattern in PATTERNS for p in root.glob(pattern)}
    problems = [f"stale: {p}" for p, text in want.items()
                if p not in have or (root / p).read_text(encoding="utf-8") != text]
    return problems + [f"orphan: {p}" for p in sorted(have - want.keys())]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="list drift and exit 1 on drift (default)")
    mode.add_argument("--write", action="store_true", help="regenerate the adapters")
    args = parser.parse_args(argv)
    try:
        problems = drift()
        if args.write:
            want = expected()
            for path, text in want.items():
                (ROOT / path).write_text(text, encoding="utf-8")
            for problem in problems:
                if problem.startswith("orphan: "):
                    (ROOT / problem.removeprefix("orphan: ")).unlink()
            problems = drift()
    except ValueError as error:
        print(f"agent-adapters: {error}", file=sys.stderr)
        return 2
    for problem in problems:
        print(f"agent-adapters: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
